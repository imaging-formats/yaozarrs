"""Every type in a public signature must be importable from a public module.

Consumers annotate the values they pass to (and get back from) yaozarrs, so each
name in a public signature must come from another package, be a public yaozarrs
object, or be exported by `yaozarrs.typing` (type aliases, which exist only for type
checkers).  A type alias defined in a private module and used in a public signature
(as `CompressionName` was, before `yaozarrs.typing`) is what this guards against.
"""

from __future__ import annotations

import ast
import builtins
import importlib
import importlib.util
import inspect
import pkgutil
import textwrap
import typing
from functools import cache
from typing import TYPE_CHECKING

import pytest

import yaozarrs
import yaozarrs.typing

if TYPE_CHECKING:
    from collections.abc import Callable, Iterator
    from types import ModuleType

TYPING_NAMES = yaozarrs.typing._TYPE_CHECKING_ONLY


def _is_private(dotted: str) -> bool:
    return any(part.startswith("_") for part in dotted.split("."))


@cache
def _public_modules() -> list[ModuleType]:
    names = [m.name for m in pkgutil.walk_packages(yaozarrs.__path__, "yaozarrs.")]
    public = [importlib.import_module(n) for n in names if not _is_private(n)]
    return [yaozarrs, *public]


@cache
def _public_ids() -> set[int]:
    """The objects that public modules export (by id)."""
    return {
        id(getattr(mod, name))
        for mod in _public_modules()
        for name in getattr(mod, "__all__", ())
    }


@cache
def _imports(module: str) -> dict[str, tuple[str, str]]:
    """{name: (source module, name there)} for each import in `module`."""
    mod = importlib.import_module(module)
    out: dict[str, tuple[str, str]] = {}
    for node in ast.walk(ast.parse(inspect.getsource(mod))):
        if isinstance(node, ast.Import):
            for alias in node.names:
                top = alias.name.partition(".")[0]
                out[alias.asname or top] = (alias.name if alias.asname else top, "")
        elif isinstance(node, ast.ImportFrom):
            source = "." * node.level + (node.module or "")
            source = importlib.util.resolve_name(source, mod.__package__)
            for alias in node.names:
                out[alias.asname or alias.name] = (source, alias.name)
    return out


def _public_functions() -> dict[Callable, str]:
    """{function: public name}, for public functions and methods of public classes."""
    out: dict[Callable, str] = {}
    for mod in _public_modules():
        for name in getattr(mod, "__all__", ()):
            obj = getattr(mod, name)
            if inspect.isfunction(obj):
                out.setdefault(obj, f"{mod.__name__}.{name}")
            elif inspect.isclass(obj):
                for cls in obj.__mro__:
                    if cls.__module__.partition(".")[0] != "yaozarrs":
                        continue
                    for attr, member in list(vars(cls).items()):
                        member = getattr(member, "__func__", member)  # (classmethod)
                        member = getattr(member, "fget", member)  # (property)
                        is_public = not attr.startswith("_") or attr.endswith("__")
                        if attr.startswith("__annotate"):
                            continue  # (generated by Python 3.14)
                        if inspect.isfunction(member) and is_public:
                            out.setdefault(member, f"{mod.__name__}.{name}.{attr}")
    return out


def _problems(func: Callable, where: str) -> Iterator[str]:
    for f in [func, *typing.get_overloads(func)]:
        node = ast.parse(textwrap.dedent(inspect.getsource(f))).body[0]
        assert isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef)
        params = inspect.signature(f).parameters
        a = node.args
        args = [*a.posonlyargs, *a.args, a.vararg, *a.kwonlyargs, a.kwarg]
        annotations = [
            (arg.annotation, params[arg.arg].default)
            for arg in args
            if arg is not None and arg.annotation is not None
        ]
        if node.returns is not None:
            annotations.append((node.returns, None))
        for annotation, default in annotations:
            for name in {n.id for n in ast.walk(annotation) if isinstance(n, ast.Name)}:
                if not _is_public(name, func, default):
                    yield f"{where}: `{ast.unparse(annotation)}` uses {name!r}"


def _is_public(name: str, func: Callable, default: object) -> bool:
    """Whether a consumer can import `name`, as used in a signature of `func`."""
    module, orig = _imports(func.__module__).get(name, (func.__module__, name))
    if module == "yaozarrs.typing":
        return orig in TYPING_NAMES
    if module.partition(".")[0] != "yaozarrs":
        return True  # (the stdlib or another package)
    if name in func.__globals__:
        obj = func.__globals__[name]
    elif hasattr(builtins, name):
        return True
    else:  # (imported or defined only for type checkers)
        obj = getattr(importlib.import_module(module), orig, None)
        if obj is None:
            return False  # (e.g. a type alias in a private module)
    if inspect.ismodule(obj):
        return not _is_private(obj.__name__)
    if isinstance(obj, typing.TypeVar) or orig in TYPING_NAMES:
        return True  # (orig: a runtime object that yaozarrs.typing re-exports)
    # (the type of a sentinel default needn't be public: callers just omit it)
    return id(obj) in _public_ids() or type(default) is obj


def test_public_signatures_use_public_types() -> None:
    problems = sorted(
        {
            p
            for func, where in _public_functions().items()
            for p in _problems(func, where)
        }
    )
    assert not problems, (
        "public signatures use names that consumers can't import (export them from "
        "a public module, or add type aliases to yaozarrs.typing):\n"
        + "\n".join(problems)
    )


def test_typing_names_are_type_checking_only() -> None:
    # `__all__`, as type checkers see it, must match its runtime copy
    static_all = next(
        ast.literal_eval(stmt.value)
        for node in ast.parse(inspect.getsource(yaozarrs.typing)).body
        if isinstance(node, ast.If)
        for stmt in node.body
        if isinstance(stmt, ast.Assign)
        and getattr(stmt.targets[0], "id", None) == "__all__"
    )
    assert set(static_all) == TYPING_NAMES
    for name in TYPING_NAMES:
        with pytest.raises(ImportError, match="if TYPE_CHECKING:"):
            getattr(yaozarrs.typing, name)
    with pytest.raises(ImportError, match="'CompressionName' cannot be imported"):
        from yaozarrs.typing import CompressionName  # noqa: F401

    # a star import gets nothing, and other names behave as usual (e.g. for tools
    # that probe a module for hooks, like pytest's `pytest_plugins`)
    namespace: dict[str, object] = {}
    exec("from yaozarrs.typing import *", namespace)
    assert set(namespace) == {"__builtins__"}
    assert getattr(yaozarrs.typing, "pytest_plugins", None) is None
    with pytest.raises(AttributeError):
        yaozarrs.typing.CompresionName  # noqa: B018
